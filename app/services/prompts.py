def _serialize_untrusted_json(payload: dict) -> str:
    """Escape delimiter characters in user-controlled JSON before embedding it."""
    encoded = json.dumps(payload, ensure_ascii=False, indent=2)
    return (
        encoded.replace("&", r"\u0026")
        .replace("<", r"\u003c")
        .replace(">", r"\u003e")
    )



